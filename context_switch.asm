[bits 32]

; ==============================================================================
; CONTEXT SWITCHING (ПЕРЕКЛЮЧЕНИЕ КОНТЕКСТА)
; ==============================================================================
; Сигнатура из C-кода (cdecl):
; void switch_context(uint32_t* old_esp, uint32_t new_esp);
; ==============================================================================

global switch_context

switch_context:
    ; ========================================================================
    ; СОХРАНЕНИЕ КОНТЕКСТА СТАРОЙ ЗАДАЧИ
    ; ========================================================================
    ; old_esp находится в [esp + 4], new_esp в [esp + 8].
    ; Сохраняем callee-saved регистры (те, что функция в C обязана беречь)
    push ebx
    push esi
    push edi
    push ebp

    ; После 4-х пушей указатели в стеке сдвинулись на +16 байт.
    ; Теперь old_esp в [esp + 20], а new_esp в [esp + 24].

    ; Загружаем в EAX указатель на поле esp в PCB старой задачи
    mov eax, [esp + 20]
    ; Сохраняем ТЕКУЩИЙ указатель стека в PCB! 
    ; Именно здесь старая задача "замораживается во времени".
    mov [eax], esp 

    ; ========================================================================
    ; ПЕРЕКЛЮЧЕНИЕ НА НОВУЮ ЗАДАЧУ
    ; ========================================================================
    ; Загружаем НОВОЕ значение указателя стека из PCB
    mov eax, [esp + 24]
    mov esp, eax    ; <--- В ЭТУ МИЛЛИСЕКУНДУ МЫ ТЕЛЕПОРТИРУЕМСЯ В ДРУГУЮ ЗАДАЧУ!

    ; ========================================================================
    ; ВОССТАНОВЛЕНИЕ КОНТЕКСТА НОВОЙ ЗАДАЧИ
    ; ========================================================================
    pop ebp
    pop edi
    pop esi
    pop ebx

    ; ========================================================================
    ; ВОЗВРАТ (MAGIC RET)
    ; ========================================================================
    ; RET делает pop EIP со стека. 
    ; Если это старая задача, там лежит настоящий адрес возврата в schedule().
    ; Если это НОВАЯ задача (только созданная в task.c), то в качестве адреса
    ; возврата там лежит её entry_point! Процессор прыгнет прямо в начало её кода.
    ret