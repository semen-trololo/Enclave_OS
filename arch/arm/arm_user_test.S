@ ==========================================================================
@ arm_user_test.S — Minimal ARM User ELF Test Image (Day 54, Task 2.4)
@ ==========================================================================
@ Этот файл собирается в build/arm/user_test.elf и затем встраивается
@ в ядро через .incbin в arch/arm/arm_user_asm.S.
@
@ Назначение:
@   - проверить ARM ELF loader
@   - проверить user stack
@   - проверить entry point
@   - проверить sys_write / sys_exit
@
@ Syscall ABI:
@   r7    = syscall number
@   r0-r6 = arguments
@   r0    = return value
@
@ Использованные syscall:
@   sys_write = 4
@   sys_exit  = 1
@ ==========================================================================

.section .text
.arm
.align 2

.global _start
.type _start, %function

_start:
    @ ------------------------------------------------------------------
    @ 1. Touch user stack.
    @
    @ Если user stack не замаплен, здесь будет Data Abort.
    @ Если стек замаплен корректно, push/pop пройдут успешно.
    @ ------------------------------------------------------------------

    mov r0, #0x42
    push {r0}
    pop {r1}

    @ ------------------------------------------------------------------
    @ 2. Build "ELF\n" on user stack.
    @
    @ Buffer layout:
    @   [sp+0] = 'E'
    @   [sp+1] = 'L'
    @   [sp+2] = 'F'
    @   [sp+3] = '\n'
    @ ------------------------------------------------------------------

    mov r0, #69                 @ 'E'
    mov r1, #76                 @ 'L'
    mov r2, #70                 @ 'F'
    mov r3, #10                 @ '\n'
    push {r0-r3}

    @ ------------------------------------------------------------------
    @ 3. sys_write(fd=1, buf=sp, len=4)
    @ ------------------------------------------------------------------

    mov r0, #1                  @ fd = stdout
    mov r1, sp                  @ buf
    mov r2, #4                  @ len
    mov r7, #4                  @ SYS_write
    svc #0

    @ ------------------------------------------------------------------
    @ 4. Restore stack.
    @ ------------------------------------------------------------------

    add sp, sp, #16

    @ ------------------------------------------------------------------
    @ 5. sys_exit(0)
    @ ------------------------------------------------------------------

    mov r0, #0                  @ exit code
    mov r7, #1                  @ SYS_exit
    svc #0

    @ ------------------------------------------------------------------
    @ Dead loop. Execution should never reach here.
    @ ------------------------------------------------------------------

1:
    b 1b

.ltorg
