#ifndef PMM_H
#define PMM_H

#include <stdint.h>
#include "multiboot.h"

// ============================================================================
// КОНСТАНТЫ PMM
// ============================================================================
#define PMM_PAGE_SIZE   4096

// ЛИМИТ БИТМАПА: Максимум для 32-битной архитектуры без PAE (4 GB).
// Битмап на 4GB занимает всего 128 KB в .bss секции ядра.
// Это позволяет PMM "видеть" всю физическую память, даже если VMM (paging.c) 
// пока делает Direct Map только на часть из них.
#define PMM_MAX_PAGES   1048576  // (4GB / 4KB)

// ============================================================================
// API ФИЗИЧЕСКОГО АЛЛОКАТОРА
// ============================================================================

// Инициализация PMM с парсингом Multiboot E820 memory map.
// Динамически вычисляет pmm_max_page на основе самого высокого адреса RAM.
void pmm_init(multiboot_info_t* info);

// Выделение физической страницы (возвращает физ. адрес или 0 при OOM)
uint32_t pmm_alloc_page(void);

// Резервирование региона памяти (запрет выделения страниц в диапазоне [base, end))
void pmm_reserve_region(uint64_t base, uint64_t end);

// Освобождение физической страницы
void pmm_free_page(uint32_t phys_addr);

// ============================================================================
// СТАТИСТИКА И ДИАГНОСТИКА
// ============================================================================

// Сколько страниц сейчас занято (выделено)
uint32_t pmm_get_used_pages(void);

// Сколько страниц свободно (доступно для аллокации)
uint32_t pmm_get_free_pages(void);

// Сколько всего страниц доступно согласно E820 (после вычета резервов)
uint32_t pmm_get_total_pages(void);

// [НОВОЕ] Динамический лимит: самый высокий номер страницы, обнаруженный в E820.
// Используется Shell для команды `meminfo` и оптимизации сканирования битмапа.
uint32_t pmm_get_max_pages(void);

// ============================================================================
// E820 MEMORY MAP (Для Shell и отладки)
// ============================================================================

// Структура для хранения записи E820 (безопасная копия для Shell)
typedef struct {
    uint64_t addr;
    uint64_t len;
    uint32_t type;
} e820_entry_t;

// Возвращает указатель на массив E820 и его размер
const e820_entry_t* pmm_get_memory_map(uint32_t* count);

// Вывод карты E820 в Serial-порт для диагностики
void pmm_dump_e820(void);

#endif // PMM_H
